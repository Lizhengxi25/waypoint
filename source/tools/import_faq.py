"""Turn the P01-P03 team's FAQ file into assistant entries.

Input: a CSV, TSV or pipe table (Markdown or copied from Teams) with the columns
Section | Question | Answer, and optionally Source and Alternative phrasings (separated by ';').
Output: src/faq_partner.js (loaded by the app) and ../data/faq_partner.csv (readable copy).

    python3 tools/import_faq.py path/to/p01p03_faq.csv --received 2026-11-24
Then rebuild (python3 build.py) and rerun tests/ai_test.py before publishing.
"""
import argparse, csv, io, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

def read_rows(path):
    text = pathlib.Path(path).read_text(encoding="utf-8-sig")
    lines = [l for l in text.splitlines() if l.strip()]
    if lines and "|" in lines[0]:
        rows = []
        for l in lines:
            cells = [c.strip() for c in l.strip().strip("|").split("|")]
            if all(re.fullmatch(r":?-{2,}:?", c) for c in cells if c):
                continue
            rows.append(cells)
    else:
        dialect = "excel-tab" if "\t" in lines[0] else "excel"
        rows = list(csv.reader(io.StringIO("\n".join(lines)), dialect=dialect))
    head = [h.strip().lower() for h in rows[0]]
    def col(*names):
        for n in names:
            if n in head:
                return head.index(n)
        return None
    ci = {"section": col("section", "topic"), "question": col("question", "q"), "answer": col("answer", "approved answer", "a"),
          "source": col("source"), "alts": col("alternative phrasings", "alternatives", "paraphrases")}
    if ci["question"] is None or ci["answer"] is None:
        sys.exit(f"Need Question and Answer columns; found {rows[0]}")
    get = lambda r, k: (r[ci[k]].strip() if ci[k] is not None and ci[k] < len(r) else "")
    return [{k: get(r, k) for k in ci} for r in rows[1:] if get(r, "question") and get(r, "answer")]

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("file"); ap.add_argument("--received", required=True, help="date the file was received, YYYY-MM-DD")
    ap.add_argument("--team", default="P01–P03 team")
    a = ap.parse_args()
    rows = read_rows(a.file)
    entries = []
    for i, r in enumerate(rows, 1):
        src = f"{a.team}, approved FAQ received {a.received}" + (f" ({r['source']})" if r["source"] else "")
        entries.append({"id": f"FAQ-D{i:02d}", "topic": r["section"] or "Placements", "q": r["question"],
                        "alts": [x.strip() for x in r["alts"].split(";") if x.strip()], "keys": [], "a": r["answer"], "source": src, "link": ""})
    js = ("/* Approved FAQ answers supplied by the " + a.team + ". Generated by tools/import_faq.py on import; do not edit by hand.\n"
          "   Loaded after ai_data.js and before ai_engine.js, so the assistant searches these entries too. */\n"
          "const FAQ_PARTNER = " + json.dumps(entries, ensure_ascii=False, indent=1) + ";\nFAQ.push(...FAQ_PARTNER);\n")
    (ROOT / "src" / "faq_partner.js").write_text(js, encoding="utf-8")
    with open(ROOT.parent / "data" / "faq_partner.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f); w.writerow(["faq_id", "topic", "question", "alternative_phrasings", "approved_answer", "source"])
        for e in entries: w.writerow([e["id"], e["topic"], e["q"], " | ".join(e["alts"]), e["a"], e["source"]])
    print(f"{len(entries)} entries written to src/faq_partner.js and data/faq_partner.csv")

if __name__ == "__main__":
    main()
