"""Load the P01-P03 team's synthetic data (student profiles and published listings) into the app.

Source: github.com/faizr206/ProjectManagement-AIRecommendation, app/data/p01p03/ipp_sample_data.json
(the P01-P03 team's export, shared with P04/P05 and P06/P07 on 24 Nov 2026).

    python3 tools/update_p01p03.py [path/to/ipp_sample_data.json]
Writes ../data/p01p03/ipp_sample_data.json (copy) and src/partner_data.js, then rebuild with python3 build.py.
"""
import json, pathlib, shutil, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
dst = ROOT.parent / "data" / "p01p03" / "ipp_sample_data.json"
if len(sys.argv) > 1:
    dst.parent.mkdir(parents=True, exist_ok=True); shutil.copy(sys.argv[1], dst)
d = json.loads(dst.read_text())
keep = {k: d[k] for k in ("_meta", "skills_vocabulary", "student_profiles", "published_listings")}
# Only the metadata the app uses (the full file stays in data/p01p03/).
keep["_meta"] = {k: d["_meta"][k] for k in ("description", "owner_team", "updated", "field_status", "rules") if k in d["_meta"]}
js = ("/* P01-P03 team's synthetic data (profiles and published listings), " + d["_meta"].get("updated", "") +
      ". Generated by tools/update_p01p03.py from data/p01p03/ipp_sample_data.json; do not edit by hand. */\n"
      "const P01P03 = " + json.dumps(keep, ensure_ascii=False, indent=1) + ";\n")
(ROOT / "src" / "partner_data.js").write_text(js, encoding="utf-8")
print(f"{len(d['student_profiles'])} profile versions, {len(d['published_listings'])} listings -> src/partner_data.js")
